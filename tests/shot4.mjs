import puppeteer from "puppeteer-core";
const OUT = process.argv[2];
const browser = await puppeteer.launch({ executablePath: "/Applications/Google Chrome.app/Contents/MacOS/Google Chrome", headless: "new", args: ["--use-angle=swiftshader", "--enable-unsafe-swiftshader"] });
const page = await browser.newPage(); await page.setViewport({ width: 1100, height: 690 });
const errs = []; page.on("pageerror", e => errs.push(e.message)); page.on("console", m => m.type() === "error" && errs.push(m.text()));
await page.evaluateOnNewDocument(() => localStorage.setItem("avtodrom.settings", JSON.stringify({ camera: "cockpit", quality: "high" })));
await page.goto("http://localhost:5179/#mashq-piyoda", { waitUntil: "networkidle0" });
const wait = ms => new Promise(r => setTimeout(r, ms));
await wait(3000);
await page.keyboard.press("KeyQ"); await page.keyboard.press("KeyH"); await wait(400);
await page.screenshot({ path: OUT + "/cobalt-cockpit.png" });
await page.keyboard.press("KeyC"); await wait(800);
await page.keyboard.down("KeyX"); await wait(1400);
await page.screenshot({ path: OUT + "/cobalt-front.png" });
await page.keyboard.up("KeyX"); await wait(900);
await page.screenshot({ path: OUT + "/cobalt-rear.png" });
console.log("errors:", errs.join(" | ") || "none");
await browser.close();
